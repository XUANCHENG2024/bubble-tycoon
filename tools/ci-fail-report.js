/**
 * CI 失败时创建 Issue（带完整诊断信息）
 *
 * ★ 为什么要它：
 *   排查「本地过 / CI 挂」这类平台差异时，
 *   **看不到失败输出就只能猜**。
 *   GitHub 的 Actions 日志要管理员权限才能下（API 返回 403），
 *   check-run 的 output 也是空的。
 *   ★ 而 Issue 是**公开可读**的 ——
 *     用 API 匿名就能拿到完整内容。
 *   ★ 这还顺带解决了「CI 失败没人知道」的问题：
 *     仓库里挂着一个红点，比藏在 Actions 里强。
 *
 * ★ 用法（CI 里）：
 *   node tools/ci-fail-report.js <测试名> <日志文件>
 *
 * ★ 为什么不用 GITHUB_TOKEN 建 Issue：
 *   默认 token 有 issues: write 权限，够用；
 *   但如果 workflow 没给这个权限，
 *   脚本会降级为「只打印」，不阻断原有流程。
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const root = path.join(__dirname, '..');

const testName = process.argv[2] || '未知测试';
const logFile = process.argv[3];

/* 读日志（没有日志文件就用 stdout 兜底） */
let log = '';
if (logFile && fs.existsSync(logFile)) {
  log = fs.readFileSync(logFile, 'utf8');
} else {
  log = '(没有日志文件 —— 用 tee 落盘后再传进来)';
}

/* ★ 日志可能很长，Issue 正文取最后 120 行 ——
   失败信息通常在末尾，而 GitHub Issue 正文有长度限制。 */
const lines = log.split('\n');
const tail = lines.slice(-120).join('\n');

const title = 'CI 失败：' + testName + '（' + new Date().toISOString().slice(0, 16).replace('T', ' ') + '）';
const body = [
  '## 失败测试',
  '',
  '`' + testName + '`',
  '',
  '## 环境',
  '',
  '- 平台：' + process.platform + ' ' + process.arch,
  '- Node：' + process.version,
  '- JSDOM_PATH：' + (process.env.JSDOM_PATH || '(未设置)'),
  '- 提交：' + (process.env.GITHUB_SHA || '(本地)'),
  '',
  '## 日志（末尾 120 行）',
  '',
  '```',
  tail,
  '```',
  '',
  '<!-- auto-generated by tools/ci-fail-report.js -->',
].join('\n');

/* ★ 先本地留一份 —— 即使 Issue 建不了，信息也没丢 */
const outDir = path.join(root, '.ci-node');
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, 'ci-fail-' + Date.now() + '.log');
fs.writeFileSync(outFile, body);
console.log('诊断信息已存到 ' + path.relative(root, outFile));

/* 尝试创建 Issue（失败不算致命 —— 原本的测试失败信息更重要） */
const token = process.env.GITHUB_TOKEN;
if (!token) {
  console.log('（无 GITHUB_TOKEN，跳过创建 Issue）');
  process.exit(0);
}

try {
  const repo = process.env.GITHUB_REPOSITORY || 'XUANCHENG2024/bubble-tycoon';
  const payload = JSON.stringify({ title, body, labels: ['ci-failure'] });
  const tmp = path.join(outDir, 'issue.json');
  fs.writeFileSync(tmp, payload);
  execFileSync('curl', [
    '-s', '-X', 'POST',
    '-H', 'Authorization: Bearer ' + token,
    '-H', 'Accept: application/vnd.github+json',
    '-H', 'Content-Type: application/json',
    '-d', '@' + tmp,
    'https://api.github.com/repos/' + repo + '/issues',
  ], { stdio: 'inherit' });
  console.log('已创建 Issue');
} catch (e) {
  console.log('创建 Issue 失败（不影响原有流程）：' + e.message);
}
process.exit(0);