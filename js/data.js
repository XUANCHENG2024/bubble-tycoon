/* ============================================================
 *  按 id 建索引
 *  这些静态表是只读的，却在渲染、结算、E2E 测试里一遍又一遍地被按 id 线性查找。
 *  建一次 Map 让查找从 O(n) 降到 O(1)，同时把散落在各处的
 *  `XXX.find(x => x.id === id)` 样板收敛成具名取值函数。
 *  依赖：必须在本文件末尾 —— 上面所有静态数组定义完成之后才执行。
 * ============================================================ */
function buildIndex(list, key) {
  const m = new Map();
  for (const it of list) m.set(it[key], it);
  return m;
}
